import { chromium } from 'file:///C:/Users/skkt3/.codex/skills/develop-web-game/node_modules/playwright/index.mjs'

const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1040, height: 1051 } })
const errors = []
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
page.on('pageerror', error => errors.push(String(error)))

await page.goto('http://192.168.0.209:5173/character-library', { waitUntil: 'networkidle' })
await page.locator('.character-card').first().click()
await page.getByRole('button', { name: '表情・顔画像' }).click()
const emotionSelect = page.getByLabel('設定する表情')
const emotionOptions = await emotionSelect.locator('option').allTextContents()
if (emotionOptions.length !== 9) throw new Error(`表情数が9ではありません: ${emotionOptions.length}`)

await emotionSelect.selectOption('joy')
await page.getByRole('button', { name: '画像一覧から選ぶ' }).click()
await page.locator('.folder-card').first().click()
const cards = page.locator('.asset-card')
if (!await cards.count()) throw new Error('画像一覧が空です')
await cards.first().click()
const joySource = await page.locator('.portrait-asset img').getAttribute('src')
if (!joySource) throw new Error('喜びの画像が設定されませんでした')
await emotionSelect.selectOption('default')
const defaultSource = await page.locator('.portrait-asset img').getAttribute('src').catch(() => null)
await emotionSelect.selectOption('joy')
const joySourceAfterSwitch = await page.locator('.portrait-asset img').getAttribute('src')
if (joySourceAfterSwitch !== joySource) throw new Error('表情切替後に喜び画像が保持されていません')
const portraitStage = page.locator('.portrait-crop-frame')
const stageBox = await portraitStage.boundingBox()
if (!stageBox) throw new Error('顔画像プレビューが見つかりません')
const offsetXInput = page.getByLabel('X位置')
const offsetYInput = page.getByLabel('Y位置')
const scaleInput = page.getByLabel('拡大率')
await page.mouse.move(stageBox.x + stageBox.width / 2, stageBox.y + stageBox.height / 2)
await page.mouse.down()
await page.mouse.move(stageBox.x + stageBox.width / 2 + 36, stageBox.y + stageBox.height / 2 + 24, { steps: 4 })
await page.mouse.up()
const draggedOffset = { x: Number(await offsetXInput.inputValue()), y: Number(await offsetYInput.inputValue()) }
if (draggedOffset.x !== 18 || draggedOffset.y !== 162) throw new Error(`2倍プレビューのドラッグ位置が正しく換算されていません: ${JSON.stringify(draggedOffset)}`)
await page.mouse.move(stageBox.x + stageBox.width / 2, stageBox.y + stageBox.height / 2)
await page.mouse.wheel(0, -120)
const wheelScale = Number(await scaleInput.inputValue())
if (wheelScale !== 2.1) throw new Error(`ホイール拡大が反映されていません: ${wheelScale}`)
await page.screenshot({ path: 'output/character-expression-tab-1040x1051.png', fullPage: false })
const characterState = await page.evaluate(() => window.render_game_to_text?.())

await page.goto('http://192.168.0.209:5173/dialogue-events', { waitUntil: 'networkidle' })
await page.locator('.event-card').first().click()
const faceDisplay = page.getByLabel('顔表示')
await faceDisplay.selectOption('plain')
const effectSelect = page.getByLabel('顔エフェクト')
if (!await effectSelect.isVisible()) throw new Error('顔なし時に顔エフェクト項目が表示されていません')
await effectSelect.selectOption('monitor')
await page.screenshot({ path: 'output/dialogue-effect-setting-1040x1051.png', fullPage: false })
await faceDisplay.selectOption('portrait')
await page.locator('.preview-line').click()
await page.waitForSelector('.dialogue-portrait.effect-monitor')
await page.screenshot({ path: 'output/dialogue-effect-section-1040x1051.png', fullPage: false })
const dialogueState = await page.evaluate(() => window.render_game_to_text?.())

console.log(JSON.stringify({ errors, emotionOptions, joySource, defaultSource, draggedOffset, wheelScale, characterState, dialogueState }, null, 2))
await browser.close()
