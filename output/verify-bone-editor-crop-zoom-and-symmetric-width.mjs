import { chromium } from 'file:///C:/Users/skkt3/.codex/skills/develop-web-game/node_modules/playwright/index.mjs'
import { join } from 'node:path'

const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 960 } })
const errors = []
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
await page.goto('http://192.168.0.209:5173/2d_bone_editor_split/', { waitUntil: 'networkidle' })
await page.locator('#projectLibraryDialog[open]').waitFor()
await page.locator('#createPixelSideProjectBtn').click()
await page.locator('.layer-item').filter({ hasText: '右上腕' }).click()
await page.locator('#replaceImageInput').setInputFiles(join('2d_bone_editor_split', 'part_templates', 'technical', 'pixel_simple', 'pixel_simple_right_arm_sample.png'))
await page.locator('#imageCropDialog[open]').waitFor()
await page.locator('#cropEditorImage').evaluate(image => image.complete ? true : new Promise(resolve => image.addEventListener('load', resolve, { once:true })))
await page.locator('#cropBoneChecks label').filter({ hasText: '左上腕' }).locator('input').check()
await page.locator('#cropWInput').fill('60')
await page.locator('#cropWInput').dispatchEvent('change')
const beforeZoom = await page.locator('#cropImageFrame').boundingBox()
const preview = await page.locator('#cropPreviewArea').boundingBox()
await page.mouse.move(preview.x + preview.width / 2, preview.y + preview.height / 2)
await page.mouse.wheel(0, -480)
await page.waitForTimeout(80)
const afterZoom = await page.locator('#cropImageFrame').boundingBox()
const zoomValue = await page.locator('#cropZoomValue').textContent()
const ranges = await page.locator('.crop-selection').evaluateAll(nodes => nodes.map(node => ({ boneId:node.dataset.boneId, left:node.style.left, width:node.style.width })))
const selected = await page.locator('.crop-selection.active').evaluate(node => ({ left:node.style.left, width:node.style.width }))
const rightHandle = await page.locator('.crop-selection.active .crop-handle.tr').boundingBox()
await page.mouse.move(rightHandle.x + rightHandle.width / 2, rightHandle.y + rightHandle.height / 2)
await page.mouse.down()
await page.mouse.move(rightHandle.x - 12, rightHandle.y + rightHandle.height / 2, { steps:3 })
await page.mouse.up()
const dragRanges = await page.locator('.crop-selection').evaluateAll(nodes => nodes.map(node => ({ boneId:node.dataset.boneId, left:node.style.left, width:node.style.width })))
await page.screenshot({ path:'output/bone-editor-crop-zoom-and-symmetric-width.png', fullPage:true })
if(!(afterZoom.width > beforeZoom.width && afterZoom.height > beforeZoom.height)) throw new Error(`ホイール拡大が反映されません: ${beforeZoom.width}x${beforeZoom.height} -> ${afterZoom.width}x${afterZoom.height}`)
if(zoomValue === '100%') throw new Error('拡大率表示が更新されません')
if(selected.left !== '20%' || selected.width !== '60%') throw new Error(`左右自動調整で中心固定の範囲になりません: ${JSON.stringify(selected)}`)
if(ranges.length !== 2 || ranges.some(range => range.left !== '20%' || range.width !== '60%')) throw new Error(`共有部位へ横範囲が揃いません: ${JSON.stringify(ranges)}`)
if(dragRanges.length !== 2 || dragRanges.some(range => range.left === '20%' || Number.parseFloat(range.width) >= 60 || range.left !== dragRanges[0].left || range.width !== dragRanges[0].width)) throw new Error(`左右ハンドルの自動調整が共有部位へ反映されません: ${JSON.stringify(dragRanges)}`)
if(errors.length) throw new Error(`console errors: ${errors.join(' | ')}`)
console.log(JSON.stringify({ beforeZoom, afterZoom, zoomValue, ranges, dragRanges, errors }, null, 2))
await browser.close()
