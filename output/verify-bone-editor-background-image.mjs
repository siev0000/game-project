import { chromium } from 'file:///C:/Users/skkt3/.codex/skills/develop-web-game/node_modules/playwright/index.mjs'

const browser=await chromium.launch({headless:true})
const page=await browser.newPage({viewport:{width:1440,height:900}})
const errors=[]
page.on('console',message=>{ if(message.type()==='error') errors.push(message.text()) })
page.on('pageerror',error=>errors.push(error.stack || error.message))
page.on('dialog',dialog=>dialog.accept())
await page.goto('http://127.0.0.1:5173/2d_bone_editor_split/',{waitUntil:'networkidle'})
await page.locator('.project-card').filter({has:page.locator('.project-card-name').filter({hasText:/^鎧デフォルト$/})}).locator('.project-card-main').click()
await page.locator('#settingsBtn').click()
await page.locator('#backgroundImageInput').setInputFiles('2d_bone_editor_split/part_templates/reference/standard_2d_modular_reference.png')
await page.locator('#backgroundXInput').fill('80')
await page.locator('#backgroundXInput').press('Tab')
await page.locator('#backgroundYInput').fill('-40')
await page.locator('#backgroundYInput').press('Tab')
await page.locator('#backgroundScaleInput').fill('60')
await page.locator('#backgroundScaleInput').press('Tab')
await page.locator('#backgroundOpacityInput').fill('35')
await page.locator('#backgroundOpacityInput').press('Tab')
await page.locator('#backgroundFlipXInput').check({force:true})
await page.locator('#backgroundFlipYInput').check({force:true})
await page.waitForTimeout(100)
await page.screenshot({path:'output/bone-editor-background-settings.png',fullPage:true})
await page.locator('#settingsCloseBtn').click()
await page.waitForTimeout(200)

const read=()=>page.evaluate(()=>{
  const project=JSON.parse(document.querySelector('#jsonArea').value)
  const image=document.querySelector('#backgroundImage')
  const layer=document.querySelector('#backgroundImageLayer')
  return {background:project.background,sourceName:project.imageSources[project.background.sourceId]?.name,display:getComputedStyle(layer).display,left:image.style.left,top:image.style.top,transform:image.style.transform,opacity:image.style.opacity,naturalWidth:image.naturalWidth}
})
const beforeReload=await read()
await page.evaluate(()=>document.querySelector('#applyJsonBtn').click())
await page.waitForTimeout(150)
const afterReload=await read()
await page.screenshot({path:'output/bone-editor-background-image.png',fullPage:true})
console.log(JSON.stringify({beforeReload,afterReload,errors},null,2))
await browser.close()
