import { chromium } from 'file:///C:/Users/skkt3/.codex/skills/develop-web-game/node_modules/playwright/index.mjs'
import { join } from 'node:path'

const browser=await chromium.launch({headless:true})
const page=await browser.newPage({viewport:{width:1440,height:960}})
const errors=[]
page.on('console',message=>{if(message.type()==='error') errors.push(message.text())})
await page.goto('http://192.168.0.209:5173/2d_bone_editor_split/',{waitUntil:'networkidle'})
await page.locator('#projectLibraryDialog[open]').waitFor()
await page.locator('#createPixelSideProjectBtn').click()
await page.locator('.layer-item').filter({hasText:'右上腕'}).click()
await page.locator('#editMeshBindingBtn').click()
await page.locator('#meshBindingDialog[open]').waitFor()
await page.locator('#meshImageInput').setInputFiles(join('2d_bone_editor_split','part_templates','technical','pixel_simple','pixel_simple_right_arm_sample.png'))
await page.locator('#meshPreviewImage').evaluate(image=>image.complete?true:new Promise(resolve=>image.addEventListener('load',resolve,{once:true})))
const beforeZoom=await page.locator('#meshPreviewFrame').boundingBox()
const overlayBeforeZoom=await page.evaluate(()=>({pointR:document.querySelector('.mesh-control-point')?.getAttribute('r'),handleR:document.querySelector('.mesh-width-handle')?.getAttribute('r'),labelSize:document.querySelector('.mesh-control-label')?.getAttribute('font-size')}))
const preview=await page.locator('#meshPreviewArea').boundingBox()
await page.mouse.move(preview.x+preview.width/2,preview.y+preview.height/2)
await page.mouse.wheel(0,-480)
await page.waitForTimeout(80)
const afterZoom=await page.locator('#meshPreviewFrame').boundingBox()
const overlayAfterZoom=await page.evaluate(()=>({pointR:document.querySelector('.mesh-control-point')?.getAttribute('r'),handleR:document.querySelector('.mesh-width-handle')?.getAttribute('r'),labelSize:document.querySelector('.mesh-control-label')?.getAttribute('font-size'),bandFill:getComputedStyle(document.querySelector('.mesh-control-band')).fill}))
const zoomValue=await page.locator('#meshZoomValue').textContent()
await page.locator('#meshPointLeftInput').evaluate(input=>{input.value='28';input.dispatchEvent(new Event('input',{bubbles:true}))})
const linkedFromSlider=await page.evaluate(()=>({left:document.querySelector('#meshPointLeftValue')?.textContent,right:document.querySelector('#meshPointRightValue')?.textContent,symmetric:(document.querySelector('#meshSymmetricWidthInput'))?.checked}))
const leftHandle=await page.locator('.mesh-width-handle.active[data-side="left"]').boundingBox()
await page.mouse.move(leftHandle.x+leftHandle.width/2,leftHandle.y+leftHandle.height/2)
await page.mouse.down()
await page.mouse.move(leftHandle.x+12,leftHandle.y+leftHandle.height/2,{steps:3})
await page.mouse.up()
const linkedFromHandle=await page.evaluate(()=>({left:document.querySelector('#meshPointLeftValue')?.textContent,right:document.querySelector('#meshPointRightValue')?.textContent}))
await page.locator('#meshPointLeftInput').evaluate(input=>{input.value='28';input.dispatchEvent(new Event('input',{bubbles:true}))})
await page.locator('#meshLockWidthInput').check()
const linePoint=await page.locator('.mesh-control-point[data-index="2"]').boundingBox()
await page.mouse.move(linePoint.x+linePoint.width/2,linePoint.y+linePoint.height/2)
await page.mouse.down()
await page.mouse.move(linePoint.x+42,linePoint.y+linePoint.height/2,{steps:3})
await page.mouse.up()
const straightPointXs=await page.locator('.mesh-control-point').evaluateAll(nodes=>nodes.map(node=>node.getAttribute('cx')))
await page.locator('.mesh-control-point[data-index="2"]').click()
const fixedAtOtherPoint=await page.evaluate(()=>({left:document.querySelector('#meshPointLeftValue')?.textContent,right:document.querySelector('#meshPointRightValue')?.textContent,locked:document.querySelector('#meshLockWidthInput')?.checked}))
await page.locator('#meshPointRightInput').evaluate(input=>{input.value='36';input.dispatchEvent(new Event('input',{bubbles:true}))})
await page.locator('.mesh-control-point[data-index="0"]').click()
const fixedAfterEdit=await page.evaluate(()=>({left:document.querySelector('#meshPointLeftValue')?.textContent,right:document.querySelector('#meshPointRightValue')?.textContent,locked:document.querySelector('#meshLockWidthInput')?.checked}))
await page.locator('#meshAddPointBtn').click()
await page.locator('#meshPointNameInput').fill('肘')
await page.locator('#meshPointTInput').evaluate(input=>{input.value='30';input.dispatchEvent(new Event('input',{bubbles:true}))})
const customPoint=await page.evaluate(()=>({label:document.querySelector('#meshActivePointLabel')?.textContent,name:document.querySelector('#meshPointNameInput')?.value,t:document.querySelector('#meshPointTValue')?.textContent,points:JSON.parse(window.render_game_to_text()).meshEditor?.points}))
const zoomArea=await page.locator('#meshPreviewArea').boundingBox()
await page.mouse.move(zoomArea.x+zoomArea.width/2,zoomArea.y+zoomArea.height/2)
for(let index=0;index<18;index++) await page.mouse.wheel(0,-480)
await page.waitForTimeout(80)
const panStart=await page.locator('#meshPreviewArea').evaluate(area=>{area.scrollTop=220; return area.scrollTop})
const panArea=await page.locator('#meshPreviewArea').boundingBox()
await page.mouse.move(panArea.x+panArea.width-60,panArea.y+panArea.height/2)
await page.mouse.down()
await page.mouse.move(panArea.x+panArea.width-60,panArea.y+panArea.height/2+80,{steps:4})
await page.mouse.up()
const panAfter=await page.locator('#meshPreviewArea').evaluate(area=>area.scrollTop)
await page.screenshot({path:'output/bone-editor-mesh-zoom-and-symmetric-width.png',fullPage:true})
if(!(afterZoom.width>beforeZoom.width || afterZoom.height>beforeZoom.height)) throw new Error(`メッシュのホイール拡大が反映されません: ${beforeZoom.width}x${beforeZoom.height} -> ${afterZoom.width}x${afterZoom.height}`)
if(zoomValue==='100%') throw new Error('メッシュ拡大率表示が更新されません')
if(!(Number(overlayAfterZoom.pointR)<Number(overlayBeforeZoom.pointR) && Number(overlayAfterZoom.handleR)<Number(overlayBeforeZoom.handleR) && Number(overlayAfterZoom.labelSize)<Number(overlayBeforeZoom.labelSize))) throw new Error(`拡大時に操作ガイドの画面上サイズが固定されません: ${JSON.stringify({overlayBeforeZoom,overlayAfterZoom})}`)
if(!linkedFromSlider.symmetric || linkedFromSlider.left!=='28%' || linkedFromSlider.right!=='28%') throw new Error(`左右自動調整のスライダー連動が不正です: ${JSON.stringify(linkedFromSlider)}`)
if(linkedFromHandle.left!==linkedFromHandle.right || Number.parseFloat(linkedFromHandle.left)>=28) throw new Error(`左右自動調整のハンドル連動が不正です: ${JSON.stringify(linkedFromHandle)}`)
if(!fixedAtOtherPoint.locked || fixedAtOtherPoint.left!=='28%' || fixedAtOtherPoint.right!=='28%') throw new Error(`横幅固定が他の関節点へ反映されません: ${JSON.stringify(fixedAtOtherPoint)}`)
if(!fixedAfterEdit.locked || fixedAfterEdit.left!=='36%' || fixedAfterEdit.right!=='36%') throw new Error(`横幅固定中の変更が全関節点へ反映されません: ${JSON.stringify(fixedAfterEdit)}`)
if(new Set(straightPointXs).size!==1) throw new Error(`直線固定で分割点が縦一直線になりません: ${JSON.stringify(straightPointXs)}`)
if(customPoint.label!=='肘' || customPoint.name!=='肘' || customPoint.t!=='30%' || customPoint.points!==5) throw new Error(`追加分割点を任意設定できません: ${JSON.stringify(customPoint)}`)
if(!(panStart>0 && panAfter<panStart)) throw new Error(`空白ドラッグでメッシュ表示を移動できません: ${JSON.stringify({panStart,panAfter})}`)
await page.locator('#meshBindingApplyBtn').click()
const savedCustomPoint=await page.evaluate(()=>{
  const saved=JSON.parse(localStorage.getItem('bone_editor_compact_single_v34'))
  const binding=Object.values(saved.meshBindings || {})[0]
  return binding?.controlPoints?.find(point=>point.name==='肘') || null
})
if(!savedCustomPoint || Math.abs(savedCustomPoint.t-.3)>.001) throw new Error(`追加分割点が保存されません: ${JSON.stringify(savedCustomPoint)}`)
if(errors.length) throw new Error(`console errors: ${errors.join(' | ')}`)
console.log(JSON.stringify({beforeZoom,afterZoom,zoomValue,overlayBeforeZoom,overlayAfterZoom,linkedFromSlider,linkedFromHandle,straightPointXs,fixedAtOtherPoint,fixedAfterEdit,customPoint,panStart,panAfter,savedCustomPoint,errors},null,2))
await browser.close()
